
// PAYSLIP PAGE
//
// Reads one payroll record and its line items and lays them out
// for printing. Nothing is calculated here — the figures were
// stored when the payroll was calculated.

import { getPayrollDetail } from './db.js';
import { COMPANY_NAME, CURRENCY } from './config.js';
const slipEl = document.getElementById('slip');
const alertEl = document.getElementById('alert');
function money(value) {
return Number(value || 0).toLocaleString('en-US', {
minimumFractionDigits: 2,
maximumFractionDigits: 2
});
}
function safe(text) {
const div = document.createElement('div');
div.textContent = text == null ? '' : String(text);
return div.innerHTML;
}
function niceMonth(value) {
if (!value) return '—';
return new Date(value + 'T00:00:00').toLocaleDateString('en-GB', {
month: 'long', year: 'numeric'
});
}
function niceDate(value) {
if (!value) return '—';
return new Date(value).toLocaleDateString('en-GB', {
day: '2-digit', month: 'short', year: 'numeric'
});
}
function showError(message) {
alertEl.className = 'alert alert--error';
alertEl.textContent = message;
alertEl.hidden = false;
slipEl.innerHTML = '';
}
function row(label, amount) {
return '<div class="slip__row">' +
'<span>' + safe(label) + '</span>' +
'<span class="num">' + money(amount) + '</span>' +
'</div>';
}
function field(label, value) {
return '<div class="slip__field">' +
'<span class="slip__label">' + label + '</span>' +
'<span class="slip__value">' + value + '</span>' +
'</div>';
}
function render(data) {
const p = data.payroll;
const slip = data.payslip;
const earnings = data.earnings.length > 0
? data.earnings.map(function (e) {
return row(e.component_name, e.amount);
}).join('')
: row('None', 0);
const deductions = data.deductions.length > 0
? data.deductions.map(function (d) {
return row(d.component_name, d.amount);
}).join('')
: row('None', 0);
slipEl.innerHTML =
'<header class="slip__head">' +
'<div>' +
'<div class="slip__company">' + safe(COMPANY_NAME) +
'</div>' +
'<div class="slip__doc">Payslip</div>' +
'</div>' +
'<div class="slip__number">' +
'<div class="mono">' +
safe(slip ? slip.payslip_number : 'Not generated') +
'</div>' +
'<div class="slip__period">' +
niceMonth(p.payroll_month) +
'</div>' +
'</div>' +
'</header>' +
'<section class="slip__who">' +
field('Employee', safe(p.full_name)) +
field('Employee ID',
'<span class="mono">' + safe(p.employee_code) +
'</span>') +
field('Department', safe(p.department_name || '—')) +
field('Designation', safe(p.designation_name || '—')) +
'</section>' +
'<section class="slip__cols">' +
'<div class="slip__col">' +
'<h3 class="slip__col-title">Earnings</h3>' +
earnings +
'<div class="slip__row slip__row--total">' +
'<span>Gross salary</span>' +
'<span class="num">' + money(p.gross_salary) + '</span>' +
'</div>' +
'</div>' +
'<div class="slip__col">' +
'<h3 class="slip__col-title">Deductions</h3>' +
deductions +
'<div class="slip__row slip__row--total">' +
'<span>Total deductions</span>' +
'<span class="num">' + money(p.total_deductions) +
'</span>' +
'</div>' +
'</div>' +
'</section>' +
'<section class="slip__net">' +
'<span class="slip__net-label">Net salary</span>' +
'<span class="slip__net-value">' +
'<span class="slip__cur">' + CURRENCY + '</span> ' +
money(p.net_salary) +
'</span>' +
'</section>' +
'<footer class="slip__foot">' +
field('Payment status',
safe(slip ? slip.payment_status : 'Pending')) +
field('Payment date',
slip && slip.payment_date
? niceDate(slip.payment_date)
: '—') +
field('Payroll status', safe(p.status)) +
field('Daily rate',
CURRENCY + ' ' + money(p.daily_rate)) +
'</footer>' +
'<p class="slip__note">' +
'This payslip is generated by the system. ' +
'Every figure is calculated from the employee salary record ' +
'and approved leave.' +
'</p>';
}
async function start() {
const params = new URLSearchParams(window.location.search);
const id = params.get('id');
if (!id) {
showError('No payroll record was given in the address.');
return;
}
try {
const data = await getPayrollDetail(id);
render(data);
} catch (err) {
showError(err.message);
}
}
document.getElementById('printBtn')
.addEventListener('click', function () {
window.print();
});

start();